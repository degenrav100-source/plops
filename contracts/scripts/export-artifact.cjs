const fs = require("fs");
const path = require("path");

const outDir = path.join(__dirname, "..", "..", "src", "contracts");
fs.mkdirSync(outDir, { recursive: true });

const CONTRACTS = [
  { contract: "PlopsBondingToken", abiConst: "PLOPS_TOKEN_ABI", bytecodeConst: "PLOPS_TOKEN_BYTECODE" },
  { contract: "PlopsFactory", abiConst: "PLOPS_FACTORY_ABI", bytecodeConst: "PLOPS_FACTORY_BYTECODE" },
  { contract: "PlopsQuotedToken", abiConst: "PLOPS_QUOTED_ABI", bytecodeConst: "PLOPS_QUOTED_BYTECODE" },
  { contract: "PlopsNFT", abiConst: "PLOPS_NFT_ABI", bytecodeConst: "PLOPS_NFT_BYTECODE" },
];

for (const { contract, abiConst, bytecodeConst } of CONTRACTS) {
  const artifactPath = path.join(
    __dirname,
    "..",
    "artifacts",
    "contracts",
    `${contract}.sol`,
    `${contract}.json`,
  );
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  const content =
    "// AUTO-GENERATED by contracts/scripts/export-artifact.cjs — do not edit by hand.\n" +
    `// Source: contracts/contracts/${contract}.sol\n` +
    `export const ${abiConst} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
    `export const ${bytecodeConst} = ${JSON.stringify(artifact.bytecode)} as const;\n`;

  const outFile = path.join(outDir, `${contract}.ts`);
  fs.writeFileSync(outFile, content);
  console.log("Wrote", outFile, `(${content.length} bytes)`);
}
